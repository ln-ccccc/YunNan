// 创建导出失败时的前端反馈决策（纯函数，项目工作台 ProjectWorkspace 与数据管理页
// DataManagerView 共用）。
//
// 背景（2026-11-23 D1）：导出由后端同步生成，项目 10 的 xlsx 台账实测约 55s。BFF 曾按
// 默认 15s 超时先回 502，而后端仍继续生成并落一条 completed 记录；旧提示「上游服务不可用，
// 请稍后重试」诱导用户重试，结果是重复建档。BFF 出站超时现已放宽到 10 分钟，失败分支
// 据此区分两种情形：
// - 结果不确定：请求可能已到达后端并仍在生成 → 先刷新导出列表，再给不诱导重试的提示；
// - 明确被拒：BFF/后端以 4xx 拒绝，不会建档 → 沿用原有提示，不做额外处理。

/**
 * 创建导出失败后，服务端是否「可能已经建档」。
 * - 有响应且为 5xx（网关超时 502/504 等）：请求已到达服务端，可能仍在生成；
 * - 无响应的 axios 请求层错误（网络中断、超时）：请求可能已发出，客户端无法确认；
 * - 有响应且为 4xx：服务端明确拒绝，不会因这次请求建档 → 沿用后端文案。后端对进行中的
 *   同格式导出回 422「正在生成中」也走这里：它明确告知了状态，不需要再当作结果不确定处理；
 * - 发请求之前就在本地抛出的普通 Error（如载荷校验）：请求未发出，不算不确定。
 */
export function isExportOutcomeUncertain(error) {
  const status = error?.response?.status;
  if (Number.isInteger(status)) {
    return status >= 500;
  }
  return error?.isAxiosError === true;
}

/**
 * 结果不确定时的提示文案。refreshed 为导出列表是否刷新成功。
 * 后端是先落一条 pending 记录再同步生成：刷新后看到的新记录可能仍是「等待处理」，要等它
 * 变成「已完成」才有下载按钮，且面板不会自动轮询，所以文案引导用户稍后刷新页面查看状态。
 * 服务端可能仍在生成，此时重复提交会重复建档，所以文案不出现「重试」。
 */
export function exportOutcomePendingMessage(refreshed) {
  if (refreshed) {
    return '导出请求未在预期时间内返回，服务端可能仍在生成。已刷新导出列表：若出现新记录，请刷新页面查看其状态，显示「已完成」后直接下载，期间不要重复提交。';
  }
  return '导出请求未在预期时间内返回，服务端可能仍在生成，但导出列表刷新失败。请稍后刷新页面确认，确认没有新记录前不要重复提交。';
}
